//! Unicode::GCString grapheme clusters as used by the pinned Biber 2.22.
//!
//! Biber's `Unicode::GCString` comes from Unicode::LineBreak 2019.001, which
//! bundles sombok 2.4.0 with Unicode 8.0.0 Grapheme_Cluster_Break data. Its
//! clusters therefore differ from current Unicode (no GB9c conjuncts, no emoji
//! ZWJ rule, unpaired regional indicators, Unicode 8 assignments). The table
//! below was extracted with `linebreak_charprop` from the oracle's
//! `LineBreak.so`; unlisted scalars are `Other`. `GCString->new($s)` uses a
//! default linebreak object (options: complex breaking only), so sombok's
//! Virama class behaves as Extend and LegacyCM is off: a cluster starting
//! with U+0020 (line break class SP) never extends.

#[derive(Copy, Clone, PartialEq, Eq)]
enum Gcb { Other, Cr, Lf, Control, Extend, SpacingMark, L, V, T, Lv, Lvt, RegionalIndicator }
use Gcb::*;

fn class(c: char) -> Gcb {
    let c = c as u32;
    match TABLE.binary_search_by(|&(start, end, _)| if end < c { std::cmp::Ordering::Less } else if start > c { std::cmp::Ordering::Greater } else { std::cmp::Ordering::Equal }) {
        Ok(index) => TABLE[index].2,
        Err(_) => Other,
    }
}

/// sombok `_gcinfo` (UAX #29, Unicode 8.0) continuation rules.
fn joins(before: Gcb, after: Gcb) -> bool {
    match (before, after) {
        (Cr, Lf) => true,
        (Cr | Lf | Control, _) | (_, Cr | Lf | Control) => false,
        (L, L | V | Lv | Lvt) | (Lv | V, V | T) | (Lvt | T, T) => true,
        (RegionalIndicator, RegionalIndicator) => true,
        (_, Extend | SpacingMark) => true,
        _ => false,
    }
}

/// Grapheme clusters exactly as `Unicode::GCString->new($s)` segments `$s`.
pub fn clusters(value: &str) -> impl Iterator<Item = &str> {
    let mut rest = value;
    std::iter::from_fn(move || {
        let mut chars = rest.char_indices();
        let (_, first) = chars.next()?;
        let mut previous = class(first);
        let mut end = rest.len();
        for (index, c) in chars {
            let current = class(c);
            if first == ' ' || !joins(previous, current) { end = index; break; }
            previous = current;
        }
        let (cluster, tail) = rest.split_at(end);
        rest = tail;
        Some(cluster)
    })
}

/// `Unicode::GCString->new($s)->length`.
pub fn length(value: &str) -> usize { clusters(value).count() }

/// Cluster start byte offsets plus the final end offset.
fn bounds(value: &str) -> Vec<usize> {
    let mut bounds = vec![0];
    for cluster in clusters(value) { bounds.push(bounds[bounds.len() - 1] + cluster.len()); }
    bounds
}

/// sombok's offset/length adjustment shared by `substr` and `replace`;
/// `None` is its out-of-range case.
fn span(clusters: usize, offset: isize, length: isize) -> Option<(usize, usize)> {
    let count = clusters as isize;
    let (mut offset, mut length) = (offset, length);
    if offset < 0 { offset += count; }
    if offset < 0 { length += offset; offset = 0; }
    if length < 0 { length += count - offset; }
    if length < 0 || count < offset { return None; }
    if count == offset { length = 0; } else if count <= offset + length { length = count - offset; }
    Some((offset as usize, length as usize))
}

/// `Unicode::GCString->new($s)->substr($offset, $length)->as_string`.
pub fn substr(value: &str, offset: isize, length: isize) -> &str {
    let bounds = bounds(value);
    match span(bounds.len() - 1, offset, length) {
        Some((offset, length)) => &value[bounds[offset]..bounds[offset + length]],
        None => "",
    }
}

/// `$gcs->substr($offset, $length, $replacement)` on `GCString->new($s)`;
/// `None` where sombok reports EINVAL (the XS croaks).
pub fn replace(value: &str, offset: isize, length: isize, replacement: &str) -> Option<String> {
    let bounds = bounds(value);
    let (offset, length) = span(bounds.len() - 1, offset, length)?;
    Some([&value[..bounds[offset]], replacement, &value[bounds[offset + length]..]].concat())
}

/// `Unicode::GCString->new($s)->substr(0, $width)`.
pub fn prefix(value: &str, width: usize) -> &str { substr(value, 0, width as isize) }

/// `Unicode::GCString->new($s)->substr(-$width, $width)`.
pub fn suffix(value: &str, width: usize) -> &str { substr(value, -(width as isize), width as isize) }

