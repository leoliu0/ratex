/// The page content of an expanded ec-lmr10 paragraph (lm.map, Type1
/// outlines): the text-matrix scale of each line (`1.02 0 0 1 x y Tm`), the
/// position of its first glyph and its text, and one font resource for all
/// the expanded and unexpanded glyphs (pdfTeX would make one font per
/// expansion).
#[test]
fn expanded_tfm_glyphs_are_scaled_in_the_pdf() {
    let mut e = run_luatex(
        r####"\outputmode=1 \pdfvariable compresslevel=0 \pdfvariable objcompresslevel=0 \pagewidth=250pt \pageheight=100pt
\pdfextension mapfile{lm.map}
\font\xf=ec-lmr10 \xf
\expandglyphsinfont\xf 20 20 5 \efcode\xf`f=400 \efcode\xf`m=0
\lpcode\xf`T=300 \rpcode\xf`.=700 \lpcode\xf`a=100 \rpcode\xf`a=200
\parindent=0pt \parfillskip=0pt plus 1fil \tolerance=10000 \pretolerance=-1 \baselineskip=12pt \hbadness=10000 \hfuzz=1000pt \righthyphenmin=62
\adjustspacing=2 \protrudechars=2 \hsize=150pt
\setbox1\vbox{away Tower Wave Away To Yo AVAVAV Wa Ty Vo yes Tavo Way aware awry watch typewriter Wow, yo yo. TAVA voyage waves.\par}
\shipout\copy1"####,
    );
    assert_clean(&e);
    let bytes = tex_core::driver::finish_pdf(&mut e, false).expect("PDF output");
    let pdf = lopdf::Document::load_mem(&bytes).expect("valid PDF");
    let page = *pdf.get_pages().values().next().expect("one page");
    let content = String::from_utf8_lossy(&pdf.get_page_content(page)).into_owned();
    // "a 0 0 1 x y Tm [(..)..]TJ" -> "a x text"
    let mut lines = Vec::new();
    let mut rest = content.as_str();
    while let Some(at) = rest.find(" Tm") {
        let nums: Vec<&str> = rest[..at].split_whitespace().rev().take(6).collect();
        let (a, x) = (nums[5], nums[1]);
        let after = &rest[at..];
        let end = after.find("]TJ").expect("TJ after Tm");
        let mut text = String::new();
        let mut depth = 0;
        for ch in after[..end].chars() {
            match ch {
                '(' if depth == 0 => depth = 1,
                ')' if depth == 1 => depth = 0,
                c if depth == 1 => text.push(c),
                _ => {}
            }
        }
        lines.push(format!("{:.2} {:.2} {}", a.parse::<f64>().unwrap(), x.parse::<f64>().unwrap(), text));
        rest = &after[end..];
    }
    assert_eq!(
        lines,
        ["1.02 -1.00 awayTowerWaveAwayToYo", "0.98 0.00 AVAVAVWaTyVoyesTavoWay", "0.98 -1.00 awareawrywatchtypewriterWow,", "1.00 0.00 yoyo.TAVAvoyagewaves."],
        "{content}"
    );
    let fonts = pdf
        .objects
        .values()
        .filter(|o| matches!(o.as_dict().ok().and_then(|d| d.get(b"Type").ok()).and_then(|t| t.as_name().ok()), Some(b"Font")))
        .count();
    assert_eq!(fonts, 1, "one font resource");
}

/// `\efcode`, `\lpcode` and `\rpcode` of a TFM font read back and assign as
/// luatex does: values are stored as given (no clamping), characters the font
/// lacks read 0 and ignore assignments, the codes are per font, and the font
/// table shows what was set. The expansion limits of a font can be set once
/// and repeated; a different limit is a fatal error.
#[test]
fn tfm_font_codes_and_limits() {
    let e = run_luatex(
        r####"\font\xf=cmr10 \xf
\message{[\the\efcode\xf`a:\the\lpcode\xf`a:\the\rpcode\xf`a:\the\efcode\xf 200:\the\efcode\xf`~]}
\efcode\xf`a=2000 \lpcode\xf`a=-5000 \rpcode\xf`a=5000 \efcode\xf 200=7
\message{[\the\efcode\xf`a:\the\lpcode\xf`a:\the\rpcode\xf`a:\the\efcode\xf 200]}
\efcode\xf`b=-5
\message{[\the\efcode\xf`b:\the\efcode\nullfont`a:\the\lpcode\nullfont`a]}
\font\yf=cmr10 at 12pt
\efcode\yf`a=5
\message{[\the\efcode\yf`a:\the\efcode\xf`a]}
\directlua{
local id = font.id("xf")
local t = font.getfont(id)
texio.write_nl("term", "<" .. tostring(t.stretch) .. ":" .. tostring(t.characters[97].expansion_factor) .. ":" .. tostring(t.characters[97].left_protruding) .. ">")
font.setexpansion(id, 30, 20, 10)
t = font.getfont(id)
texio.write_nl("term", "<" .. tostring(t.stretch) .. ":" .. tostring(t.shrink) .. ":" .. tostring(t.step) .. ">")
}
\expandglyphsinfont\xf 30 20 10 \message{}
\directlua{local t = font.getfont(font.id("xf")) texio.write_nl("term", "<" .. t.stretch .. ":" .. t.shrink .. ":" .. t.step .. ">")}
\expandglyphsinfont\yf 40 0 10 \message{}
\directlua{local t = font.getfont(font.id("yf")) texio.write_nl("term", "<" .. t.stretch .. ":" .. tostring(t.shrink) .. ":" .. t.step .. ">")}
"####,
    );
    assert_clean(&e);
    let term = e.term.replace('\n', "");
    for want in ["[1000:0:0:0:1000]", "[2000:-5000:5000:0]", "[-5:0:0]", "[5:2000]", "<nil:2000:-5000>", "<30:20:10>", "<40:nil:10>"] {
        assert!(term.contains(want), "missing {want} in {term}");
    }
}

/// A different stretch limit for an expanded font stops the run: luatex
/// `normal_error`.
#[test]
fn different_expansion_limit_is_fatal() {
    let e = run_luatex(
        r####"\font\xf=cmr10 \xf
\expandglyphsinfont\xf 20 20 5
\expandglyphsinfont\xf 20 20 5
\expandglyphsinfont\xf 25 20 5
\message{notreached}"####,
    );
    assert_eq!(e.error_count, 1, "{:?}", e.diagnostics);
    assert!(e.diagnostics.iter().any(|d| d.message.contains("(font expansion): font has been expanded with different stretch limit")));
    assert!(!e.term.contains("notreached"));
}
