fn block(par: &str, adj: i32, prot: i32, hsize: i32) -> String {
    format!("\\adjustspacing={adj} \\protrudechars={prot} \\hsize={hsize}pt \\setbox1\\vbox{{{par}\\par}}\n\\directlua{{check(tex.box[1])}}\n")
}

/// Every combination of `\adjustspacing` 2, 1 and 3, `\protrudechars` 2 and
/// 1 and two line widths on a paragraph with many font kerns, then two
/// protrusion-only paragraphs.
fn matrix(font: &str) -> String {
    let mut s = format!("{font}\n\\expandglyphsinfont\\xf 20 20 5 \\efcode\\xf`f=400 \\efcode\\xf`m=0 {PROT}\n");
    for adj in [2, 1, 3] {
        for prot in [2, 1] {
            for hs in [150, 120] {
                s += &block(KERNPARA, adj, prot, hs);
            }
        }
    }
    s += &block(PARA, 2, 2, 110);
    s += &block(PARA, 2, 1, 90);
    s
}

