//! Font expansion and character protrusion of fonts loaded from TFM files in
//! LuaTeX (`\font`, `\expandglyphsinfont`, `\efcode` / `\lpcode` / `\rpcode`,
//! `\adjustspacing`, `\protrudechars`). Expected values come from
//! `luatex --ini` (TeX Live 2026) running the same input: each case sets a
//! paragraph or an hbox and compares what the lines hold, i.e. width, glue
//! set and sign, the margin kerns (side, width, character and its expansion),
//! the `expansion_factor` of the glyphs (run lengths), ligatures, and of the
//! font kerns.

use tex_core::engine::{Engine, EngineKind};

static HERMETIC: std::sync::Once = std::sync::Once::new();

fn run_luatex(body: &str) -> Engine {
    HERMETIC.call_once(|| {
        std::env::set_var("TEX_RS_HERMETIC", "1");
        // kpathsea's `abs_fname_ok` wants a file name below TEXMFOUTPUT to
        // continue with a separator right after it: macOS's $TMPDIR ends in
        // `/`, which `temp_dir()` keeps, so no name would be below it.
        std::env::set_var("TEXMFOUTPUT", std::env::temp_dir().components().collect::<std::path::PathBuf>());
    });
    let mut e = Engine::new_with_kind(EngineKind::LuaTeX, true);
    e.init_primitives();
    e.add_nullfont();
    for (c, cat) in [(b'{', 1), (b'}', 2), (b'#', 6), (b' ', 10), (b'\n', 5)] {
        e.eqtb.cat[c as usize] = cat;
    }
    e.input.push_file(
        "t.tex".to_string(),
        format!("\\directlua{{tex.enableprimitives('',tex.extraprimitives())}}\n{body}\n\\end\n").into_bytes(),
    );
    e.run();
    e
}

fn assert_clean(e: &Engine) {
    assert_eq!(e.error_count, 0, "errors: {:?}\n{}", e.diagnostics, e.term);
}

/// Lua that summarises the lines of `tex.box[1]` and appends the summary to
/// the file `out` for `check()`.
fn check_lua(out: &std::path::Path) -> String {
    let out = out.to_string_lossy().replace('\\', "/");
    format!(
        r####"\begingroup\catcode`\%=12 \catcode`\#=12 \directlua{{
local nl = string.char(10)
local function r4(x) return tostring(math.floor(x * 10000 + 0.5) / 10000) end
local function summary(box)
 local out = {{}}
 for l in node.traverse_id(node.id("hlist"), box.list) do
  local parts = {{"w=" .. l.width .. " gs=" .. r4(l.glue_set) .. " sign=" .. l.glue_sign}}
  local last, run = nil, 0
  local function flush() if run > 0 then parts[#parts+1] = last .. "x" .. run end last, run = nil, 0 end
  for n in node.traverse(l.list) do
   if n.id == node.id("glyph") then
    if math.floor(n.subtype / 2) % 2 == 1 then flush(); parts[#parts+1] = "lig" .. n.char .. ":" .. n.expansion_factor
    elseif n.expansion_factor == last then run = run + 1 else flush(); last, run = n.expansion_factor, 1 end
   elseif n.id == node.id("margin_kern") then
    flush(); parts[#parts+1] = "mk" .. n.subtype .. ":" .. n.width .. ":" .. n.glyph.char .. ":" .. n.glyph.expansion_factor
   elseif n.id == node.id("disc") then
    flush(); parts[#parts+1] = "disc"
   elseif n.id == node.id("kern") and n.expansion_factor ~= 0 then
    flush(); parts[#parts+1] = "k" .. n.kern .. ":" .. n.expansion_factor
   end
  end
  flush()
  out[#out+1] = table.concat(parts, " ")
 end
 return table.concat(out, nl)
end
function check(box)
 local fh = io.open([==[{}]==], "a"); fh:write(summary(box), nl, "--", nl); fh:close()
end
}}\endgroup
\parindent=0pt \parfillskip=0pt plus 1fil \tolerance=10000 \pretolerance=-1 \baselineskip=12pt \hbadness=10000 \hfuzz=1000pt \righthyphenmin=62
"####,
        out
    )
}

/// Run `body` after the summary setup; returns what `check` collected, one
/// entry per call.
fn collect(name: &str, body: &str) -> Vec<String> {
    let out = std::env::temp_dir().join(format!("ratex-tfm-expansion-{}-{name}.sum", std::process::id()));
    let _ = std::fs::remove_file(&out);
    let e = run_luatex(&format!("{}{body}", check_lua(&out)));
    assert_clean(&e);
    let text = std::fs::read_to_string(&out).unwrap_or_default();
    let _ = std::fs::remove_file(&out);
    text.split("\n--\n").filter(|s| !s.is_empty()).map(|s| s.trim_end_matches("\n--").to_string()).collect()
}

fn assert_summaries(got: Vec<String>, expected: &[&str]) {
    assert_eq!(got.len(), expected.len(), "number of checks");
    for (i, (g, e)) in got.iter().zip(expected).enumerate() {
        assert_eq!(g, e, "check {i}");
    }
}

