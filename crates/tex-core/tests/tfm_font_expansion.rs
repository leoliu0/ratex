/// Six fonts with different stretch, shrink and step limits (including a
/// font that cannot shrink and one that cannot stretch).
#[test]
fn expansion_limits_and_steps() {
    let limits = [(40, 10, 10), (10, 40, 10), (30, 30, 3), (100, 50, 50), (20, 0, 5), (0, 20, 5)];
    let mut body = String::new();
    for (i, (st, sh, step)) in limits.into_iter().enumerate() {
        let f = format!("yf{}", (b'a' + i as u8) as char);
        body += &format!(
            "\\font\\{f}=ec-lmr10 at {}pt \\{f} \\expandglyphsinfont\\{f} {st} {sh} {step} \\adjustspacing=2 \\protrudechars=0 \\hsize=140pt \\setbox1\\vbox{{\\{f} {KERNPARA}\\par}}\n\\directlua{{check(tex.box[1])}}\n",
            10 + i
        );
    }
    assert_summaries(collect("limits", &body), &T_LIMITS);
}

/// Ligatures (`ff`, `fi`, `ffi`, ...) are glyphs that expand like any other,
/// with a high `\efcode` of `f`.
