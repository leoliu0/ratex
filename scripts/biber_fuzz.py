#!/usr/bin/env python3
"""Randomized, byte-exact differential testing against Biber 2.22.

Example (run after building the candidate):
  python scripts/biber_fuzz.py --biber /path/to/biber --seed 222 --count 2000 \
      --jobs 8 --failures-dir /tmp/biber-fuzz-failures

Every index independently generates a new bibliography and document. A seeded
pool of 64 document-control profiles spans styles, options and citation/context
layouts. BCFs are generated by /usr/bin/pdflatex once per exact control profile;
only plain, non-bibliographic prose varies within a profile. Biblatex's first
pass with backend=biber does not read the bibliography. No BBL is reused or
normalized. --no-bcf-cache generates the BCF from every actual document instead.

TeX Live's kpathsea has no getcwd(): it finds the working directory by reading
each ancestor directory and stat()ing its entries, and any entry deleted in
between aborts pdflatex ("pdflatex: NAME: No such file or directory"). Every
child therefore gets a private TMPDIR (Biber creates and removes biber_tmp_XXXX
there), pdflatex runs below a tree that no other worker deletes from, and a
generation aborted by deletions elsewhere in an ancestor (e.g. $HOME) is rerun.

Failures contain both isolated executions, original inputs, BCF provenance,
a complete byte/text difference report and replay metadata. --start INDEX
--count 1 reproduces an index without executing its predecessors. Oracle/oracle
runs exercise this runner, NOT candidate compatibility. Exit codes: 0 match,
1 differences/execution failures, 2 invalid configuration.
"""

